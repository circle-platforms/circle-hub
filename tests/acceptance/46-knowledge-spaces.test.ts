// Decision 84 phase 2 over the real assembly and official MCP client, with no products or business systems.
import assert from 'node:assert/strict';
import { after, before, test } from 'node:test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { writePack } from '../../hub/runs/api.ts';
import { reviewPack, REVIEW_PACK } from '../../hub/server/assemble/test-packs.ts';
import { openConsole } from './support/console.ts';
import { createTestHub, type TestHub } from '../../hub/server/testing-real.ts';
import { connect, type McpClient, type Answer, type Outputs } from './support/mcp.ts';
let packDirectory: string;
let hub: TestHub, owner: Awaited<ReturnType<TestHub['createUser']>>, other: typeof owner;
let client: McpClient, outsider: McpClient, admin: McpClient;
before(async () => {
  packDirectory = await mkdtemp(join(tmpdir(), 'knowledge-spaces-packs-'));
  const pack = await writePack(join(packDirectory, 'review'), reviewPack());
  hub = await createTestHub({ repositoryPacks: false, packs: [pack.dir], stubs: false, mindmapSkill: true, workbookSkill: false, xmlSkill: false, htmlSkill: false });
  owner = await hub.createUser('合成空间成员');
  other = await hub.createUser('合成空间读者');
  client = await connect(hub, owner.token);
  outsider = await connect(hub, other.token);
  admin = await connect(hub, hub.admin.token);
});
after(async () => { await client?.close(); await outsider?.close(); await admin?.close(); await hub?.close(); await rm(packDirectory, { recursive: true, force: true }); });
test('personal entry writes, scoped full-text search and revoked tree references cross all package boundaries', async () => {
  const saved = await client.call('upload_file', { personal_entry: { kind: 'observation', statement: '合成空间中保存的可检索观察', path: '/notes' } });
  assert.equal(saved.isError, false, saved.text);
  const entry = saved.out.personal_entry;
  assert.ok(entry);
  assert.equal(entry.status, 'unverified');
  assert.match(saved.text, /个人条目已保存/);
  assert.ok(saved.text.includes(entry.reference));
  const read = await client.call('get_nodes', { space: owner.user.id, paths: ['/notes'] });
  assert.equal(read.isError, false, read.text);
  assert.equal(read.out.nodes?.[0].entries[0].entry, entry.entry);
  const search = await client.call('get_nodes', { search: '可检索观察', scope: 'personal' });
  assert.equal(search.isError, false, search.text);
  assert.equal(search.out.matches?.length, 1);
  for (const denied of [outsider, admin]) {
    const answer: Answer<Outputs['get_nodes']> = await denied.call('get_nodes', { reference: entry.reference });
    assert.equal(answer.isError, true);
    assert.ok(!answer.text.includes('保存的可检索观察'));
  }
  await hub.hub.knowledge.spaces!.grant(owner.principal, { path: '/notes', audience: 'member', member: other.user.id });
  assert.equal((await outsider.call('get_nodes', { reference: entry.reference })).isError, false);
  assert.equal((await outsider.call('get_nodes', { search: '可检索观察', scope: 'shared' })).out.matches?.length, 1);
  const resolved = await outsider.call('resolve_reference', { root: entry.root, text: entry.reference });
  assert.equal(resolved.isError, false, resolved.text);
  assert.equal(resolved.out.resolution, 'resolved');
  await hub.hub.knowledge.spaces!.grant(owner.principal, { path: '/notes', audience: 'member', member: other.user.id, revoke: true });
  assert.equal((await outsider.call('get_nodes', { reference: entry.reference })).isError, true);
  const refused = await client.call('get_nodes', { run: 'run_00000000000000000000000001', search: '合成空间', scope: 'all' });
  assert.equal(refused.out.errors[0].code, 'SPACE_SEARCH_IN_RUN');
  const log = (await hub.records.callLog.query(hub.admin.principal, { tool: 'upload_file', limit: 1 })).items[0];
  assert.equal(log.args_preview, null);
});
test('private source imports verify exact quotations and capacity errors keep their registered codes through MCP', async () => {
  const source = await client.call('upload_file', { file_path: Buffer.from('合成来源：处理两项。').toString('base64'), media_type: 'text/plain', name: 'synthetic.txt', space: 'personal' });
  assert.equal(source.isError, false, source.text);
  assert.ok(source.out.reference);
  assert.equal((await admin.call('get_nodes', { reference: source.out.reference })).isError, true);
  const saved = await client.call('upload_file', { personal_entry: { kind: 'observation', statement: '合成已核验的观察', grounds: [{ reference: source.out.reference, quotation: '处理两项' }] } });
  assert.equal(saved.isError, false, saved.text);
  assert.equal(saved.out.personal_entry?.status, 'verified');
  const bad = await client.call('upload_file', { personal_entry: { kind: 'observation', statement: '合成错误引文', grounds: [{ reference: source.out.reference, quotation: '处理三项' }] } });
  assert.equal(bad.out.errors[0].code, 'SPACE_ENTRY_INVALID');
  await hub.hub.knowledge.spaces!.setCapacity(hub.admin.principal, owner.user.id, 0);
  const limited = await client.call('upload_file', { personal_entry: { kind: 'observation', statement: '合成超出容量' } });
  assert.equal(limited.out.errors[0].code, 'SPACE_CAPACITY_EXCEEDED');
  await hub.hub.knowledge.spaces!.setCapacity(hub.admin.principal, owner.user.id, 1024 ** 3);
});
// A real workflow freezes both spaces; extra permissions of an administrator cannot enlarge its initiator scope.
test('run space locks survive later writes and administrator reads remain limited to the initiator', async () => {
  await hub.assignPack(owner.principal, REVIEW_PACK);
  const spaces = hub.hub.knowledge.spaces!;
  const locked = await spaces.write(owner.principal, { kind: 'observation', statement: '合成锁定的笔记', path: '/run-notes' });
  const node = (id: string, text: string, children: unknown[] = [], data: Record<string, unknown> = {}) => ({ data: { id, text, ...data }, children });
  const map = { root: node('r1', '合成脑图', [node('c1', '合成用例', [node('e1', '合成期望')], { resource: ['合成功能'] })]), template: 'default', theme: 'fresh-blue', version: '1.4.43' };
  const uploaded = await client.call('upload_file', { file_path: Buffer.from(JSON.stringify(map)).toString('base64'), name: 'map.json' });
  assert.equal(uploaded.isError, false, uploaded.text);
  const started = await client.call('start_run', { pack: REVIEW_PACK, inputs: { map: { reference: uploaded.out.reference } } });
  assert.equal(started.isError, false, started.text);
  const run = started.out.run!;
  assert.equal(run.knowledge_spaces?.personal, locked.root);
  assert.equal(run.knowledge_spaces?.owner, owner.user.id);
  assert.ok(run.knowledge_spaces?.team);
  const later = await spaces.write(owner.principal, { kind: 'observation', statement: '合成后来添加的笔记', path: '/run-notes' });
  const frozen = await client.call('get_nodes', { run: run.run, space: owner.user.id, paths: ['/run-notes'] });
  assert.equal(frozen.isError, false, frozen.text);
  assert.equal(frozen.out.root, locked.root);
  assert.equal(frozen.out.nodes?.[0].entries.length, 1);
  assert.equal((await client.call('get_nodes', { run: run.run, reference: later.reference })).isError, true);
  assert.equal((await client.call('resolve_reference', { run: run.run, text: locked.reference })).out.resolution, 'resolved');
  assert.equal((await client.call('resolve_reference', { run: run.run, text: later.reference })).out.resolution, 'unresolved');
  const privateAdmin = await spaces.write(hub.admin.principal, { kind: 'observation', statement: '合成管理员私有笔记', path: '/notes' });
  const adminRead = await admin.call('get_nodes', { run: run.run, reference: privateAdmin.reference });
  assert.equal(adminRead.isError, true);
  assert.ok(!adminRead.text.includes('管理员私有笔记'));
  await spaces.grant(hub.admin.principal, { path: '/notes', audience: 'member', member: owner.user.id });
  assert.equal((await client.call('get_nodes', { run: run.run, reference: privateAdmin.reference })).isError, false);
  await spaces.grant(hub.admin.principal, { path: '/notes', audience: 'member', member: owner.user.id, revoke: true });
  assert.equal((await client.call('get_nodes', { run: run.run, reference: privateAdmin.reference })).isError, true);
});

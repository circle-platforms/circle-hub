// A fresh scripted client has the existing target/product context and predecessor; no receipt reference is handed to it.
import assert from 'node:assert/strict';
import {after,before,test} from 'node:test';
import type {ValidationResult} from '../../contracts/src/validation.ts';
import {startPostgres,type TemporaryPostgres} from '../../hub/testing/postgres.ts';
import {INDEX} from '../../hub/runs/engine/store.ts';
import {DOCUMENTS} from '../fixtures/agile/index.ts';
import {openBed,type Bed} from './support/hub.ts';
import type {McpClient} from './support/mcp.ts';
import {draft,startReview} from './support/review.ts';
let pg:TemporaryPostgres,bed:Bed,author:McpClient,verifier:McpClient;
before(async()=>{pg=await startPostgres();bed=await openBed({postgres:pg});author=await bed.connect(bed.reviewer,'synthetic-default-drafter');verifier=await bed.connect(bed.reviewer,'synthetic-default-verifier');});
after(async()=>{await bed?.close();await pg?.stop();});
test('a fresh review client starts from the predecessor without copying a receipt reference and explicit input still wins',async()=>{
  const source={external:`agile:mindmap:${DOCUMENTS.review}`};
  const initial=await startReview(author,{product:bed.product.names[0],version:bed.site.LINE,inputs:{subject:source}});
  const submitted=await author.call('submit_result',draft(initial));assert.equal(submitted.out.acceptance,'accepted',submitted.text);
  const expected=(await bed.hub.deps.runs.getRun(bed.reviewer.principal,initial.run))!.latest!;
  const refused=await author.call('submit_result',{run:initial.run,model:'synthetic-drafter',items:[{item:'synthetic-missing-item',handling:'skipped',reason:'合成反例'}]});
  assert.equal(refused.out.acceptance,'not_accepted');assert.ok(refused.out.result);
  const rejected=(await bed.hub.records.store.find<ValidationResult>({kind:'validation_result',key:INDEX.resultSubmission,value:initial.run+':'+refused.out.result.submission,limit:1,newestFirst:true})).items[0];assert.ok(rejected);
  const input={pack:'case-review-verify',product:bed.product.names[0],version:bed.site.LINE,predecessor:initial.run,inputs:{target:source}};
  const started=await verifier.call('start_run',input);
  assert.equal(started.out.call_result,'ok',started.text);assert.ok(started.out.run);
  const defaults=[{slot:'draft',predecessor:initial.run,reference:'rec:'+expected.record}];
  assert.deepEqual(started.out.run.input_defaults,defaults);
  assert.equal(started.out.run.sources.find(s=>s.slot==='draft')!.reference,defaults[0].reference);
  assert.ok(started.text.includes(`draft 按前驱 ${initial.run} 的已受理结果 ${defaults[0].reference} 绑定`));
  const listed=await verifier.call('list_task_packs',{});
  assert.deepEqual(listed.out.packs.find(p=>p.id==='case-review-verify')!.inputs.find(i=>i.slot==='draft')!.default_from_predecessor,{pack:'case-review'});
  const stored=(await bed.hub.records.store.find<{input_defaults:unknown}>({kind:'run',key:INDEX.runId,value:started.out.run.run,limit:1})).items[0];
  assert.deepEqual(stored.body.input_defaults,defaults);
  const read=await verifier.call('get_nodes',{reference:'rec:'+stored.digest+'#/input_defaults'});
  assert.equal(read.isError,false,read.text);assert.ok(read.text.includes(expected.record));
  const explicit=await verifier.call('start_run',{...input,inputs:{...input.inputs,draft:{reference:defaults[0].reference}}});
  assert.equal(explicit.out.call_result,'ok',explicit.text);assert.equal(explicit.out.run!.input_defaults,undefined);
  const invalid=await verifier.call('start_run',{...input,inputs:{...input.inputs,draft:{reference:'rec:'+rejected.digest}}});
  assert.equal(invalid.out.call_result,'error');assert.ok(invalid.out.errors.some(e=>e.code==='case-review-verify.draft_not_accepted'),'the package checks the explicit rejected record; the Hub must not replace it');
  const pending=await startReview(author,{product:bed.product.names[0],version:bed.site.LINE,inputs:{subject:source}});
  const missing=await verifier.call('start_run',{...input,predecessor:pending.run});
  assert.equal(missing.out.call_result,'error');assert.ok(missing.out.errors.some(e=>e.code==='SUBMISSION_SCHEMA_VIOLATION'&&e.path==='/inputs/draft'&&e.fix?.includes('先让前驱运行按回执改正并重新提交，被受理后再开始复核')));
});

// Generate only the label snapshot used by this pack from the authoritative generated vocabulary.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { PROVENANCE_TYPE_LABEL } from '../../../../contracts/generated/vocabulary.ts';
export function vocabularyText(): string {
  return '// Generated by testing/generate-vocabulary.ts; do not edit.\n' +
    "import type { ProvenanceType } from '../../../../../contracts/generated/vocabulary.ts';\n" +
    `export const PROVENANCE_TYPE_LABEL = ${JSON.stringify(PROVENANCE_TYPE_LABEL, null, 2)} as const satisfies Record<ProvenanceType, string>;\n` +
    "export function labelOf(axis: 'provenance_type', value: ProvenanceType): string { return PROVENANCE_TYPE_LABEL[value]; }\n";
}
if (import.meta.main) {
  const directory = new URL('../functions/generated/', import.meta.url); const file = new URL('vocabulary.ts', directory);
  if (process.argv[2] === '--check') process.exitCode = await readFile(file, 'utf8').catch(() => '') === vocabularyText() ? 0 : 1;
  else { await mkdir(directory, { recursive: true }); await writeFile(file, vocabularyText()); }
}

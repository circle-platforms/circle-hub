import assert from 'node:assert/strict';
import {test} from 'node:test';
import {readFileSync} from 'node:fs';
import {blockSchema} from './gen-block-schema.ts';
import TABLE from '../tables/blocks-format.json' with {type:'json'};
const json=(path:string)=>JSON.parse(readFileSync(new URL('../'+path,import.meta.url),'utf8'));
test('published block and criterion schemas are exactly derived from the package declaration',()=>{
 const declared=blockSchema(),slots=json('slots.schema.json').item.plan.data.properties;
 assert.deepEqual(slots.blocks.items,declared.block);assert.deepEqual(slots.block_context,declared.context);assert.deepEqual(slots.criteria.items,declared.criterion);assert.deepEqual(slots.obligations.items,declared.obligation);
 assert.deepEqual(json('tables/block-plan.schema.json').properties.blocks.items,declared.block);
 assert.deepEqual(json('review/tables/criterion.schema.json'),declared.criterion);
 assert.deepEqual(declared.block.anyOf.map(row=>(row.properties.kind as {const:string}).const),TABLE.kinds.map(row=>row.kind));
 const validator=readFileSync(new URL('../functions/schema.ts',import.meta.url),'utf8').replace("import {addressValue} from './manifest.ts';","// Criterion schemas declare no address formats; unexpected formats fail closed.\nconst addressValue=(_kind:string,_value:string):null=>null;");
 assert.equal(readFileSync(new URL('../review/functions/schema.ts',import.meta.url),'utf8'),'// Generated by case-compile/testing/gen-block-schema.ts; do not edit.\n'+validator);
});

import assert from 'node:assert/strict';
import {after,before,test} from 'node:test';
import {accepted,runRecord} from '../../../contracts/src/fixtures.ts';
import {ValidationResult} from '../../../contracts/src/validation.ts';
import {RunRecord} from '../../../contracts/src/run.ts';
import {digestOf} from '../../records/api.ts';
import {openTestRecords,type TestRecordsKit} from '../../testing/records.ts';
import {startPostgres,type TemporaryPostgres} from '../../testing/postgres.ts';
import {createEngineContext} from './deps.ts';
import {putRun,putAction,putResult,putSubmission,resultFor,latestAccepted} from './store.ts';
import {getRun,getResult,listRuns} from './queries.ts';
let pg:TemporaryPostgres,kit:TestRecordsKit;
before(async()=>{pg=await startPostgres();kit=await openTestRecords({postgres:pg});});
after(async()=>{await kit?.close();await pg?.stop();});
test('system delivery inputs are reproducible and never alias a received user submission with identical bytes',async()=>{
  const admin=(await kit.principals.bootstrapAdmin('合成管理员')).user;
  const at='2026-10-24T00:00:00.000Z';
  const run=RunRecord.parse({...runRecord,runner:admin.id,version:'10.6',build:'rel_demo_10_6_1',started_at:at,submission_due:'2026-10-26T00:00:00.000Z'});
  const stored=await putRun(kit.store,run,at);
  const input={run:run.run,run_record:stored.digest,observed_at:at,submission_due:run.submission_due};
  const action=await putAction(kit.store,{action:'validate',run:run.run,inputs:['rec:'+stored.digest],startedAt:at,endedAt:at,acceptance:null,codes:[],detail:{input,system_delivery:true}});
  const result=ValidationResult.parse({...accepted,run:run.run,submission:digestOf(input),system_input:'rec:'+action.digest});
  const saved=await putResult(kit.store,result,at);
  assert.equal(saved.body.submission,digestOf((await kit.store.get<{detail:{input:unknown}}>(action.digest))!.body.detail.input));
  assert.equal(await resultFor(kit.store,run.run,result.submission),null,'system results never occupy user submission indexes');
  assert.equal((await latestAccepted(kit.store,run.run))?.digest,saved.digest);
  await putSubmission(kit.store,{run:run.run,digest:result.submission,body:input,parses:false,createdAt:at});
  const ctx=createEngineContext({records:kit,workflows:{} as never,packs:{} as never,knowledge:{} as never,external:{} as never});
  const detail=(await getRun(ctx,admin,run.run))!;
  assert.equal(detail.submissions[0].acceptance,null,'an interrupted malformed user submission is not the system delivery');
  assert.equal(detail.submissions[0].result,null);
  const bob=await kit.principals.createUser(admin,'合成分享读者');
  await kit.authorizations.share(admin,run.run,[bob.id]);
  const shared=(await getRun(ctx,bob,run.run))!;
  assert.equal(shared.latest!.record,saved.digest);
  assert.equal(shared.submissions[0].result,null,'a shared system delivery also never aliases a user receipt');
  assert.deepEqual(shared.requests,[]);
  assert.equal((await getResult(ctx,bob,run.run))!.record,saved.digest);
  assert.equal((await listRuns(ctx,bob,{limit:1})).items[0].run,run.run);

});

test('abandon is an authenticated administrative delivery, not a successful target verdict or an unfreeze', {skip},async()=>{
  const map=await h.upload(h.alice,toyMap(standardDocument()));
  const run=(await h.service.startRun(h.alice,{pack:'toy-review',product:'Meadow',version:'10.6.1',build:'Rel_MEADOW_10_6_1_7',submission_due:'2026-10-22T08:01:00.000Z',inputs:{map:{reference:map}}},h.call())).run!;
  h.advance(120000);await h.service.maintain();
  const before=(await h.service.getRun(h.alice,run.run))!.latest!;
  const question=(await h.service.listRequests!(h.alice,run.run)).find(r=>r.kind==='disposition'&&!r.item&&!r.requirement)!;
  await assert.rejects(h.service.abandonRun!(h.bob,run.run,question.record,'合成放弃理由'));
  const answer=await h.service.abandonRun!(h.alice,run.run,question.record,'合成放弃理由');
  assert.ok(answer.result.system_input);
  assert.equal(answer.result.partitions.delivered.length,run.items.length);
  assert.ok(answer.result.partitions.delivered.every(i=>i.requirements.every(r=>r.status==='unsatisfied'&&r.unsatisfied_reason==='abandoned')));
  const source=await h.kit.store.get<{detail:{input:unknown}}>(answer.decision);
  assert.equal(answer.result.submission,(await import('../../records/api.ts')).digestOf(source!.body.detail.input));
  assert.deepEqual((await h.kit.store.get(before.record))!.body,before.result,'the old result bytes are untouched');
  assert.equal((await h.service.abandonRun!(h.alice,run.run,question.record,'合成放弃理由')).record,answer.record);
  const rejected=await h.service.submitResult(h.alice,{run:run.run,model:'synthetic',items:[]},h.call());
  assert.equal(rejected.acceptance,'not_accepted');assert.equal(rejected.errors[0].code,'RUN_ABANDONED');
  assert.equal((await h.kit.store.find({kind:'submission',key:INDEX.submissionRun,value:run.run})).items.length,1);
  assert.equal((await h.service.getRun(h.alice,run.run))!.latest!.record,answer.record);
});
test('legacy missing exits use only this real management request in the new projection and preserve unknown counts', {skip},async()=>{
  const map=await h.upload(h.alice,toyMap(standardDocument()));
  const start=await h.service.startRunDetailed(h.alice,{pack:'toy-locate',inputs:{map:{reference:map}}},h.call());const run=start.answer.run!;
  const old=structuredClone(start.production!.result),layer=old.partitions.delivered[0].requirements[0];
  layer.layers=[{layer:'static',terminal:'unchecked',reason:'check_error'}];layer.status='pending';delete layer.unsatisfied_reason;
  const record=await h.kit.store.put({kind:'validation_result',schema:'validation@1',provenance:'projected',body:old,index:[{key:INDEX.resultRun,value:run.run}]});
  const stored=(await runById(h.kit.store,run.run))!;
  const question=await createRequestService(h.kit).write({run:run.run,kind:'disposition',audience:h.alice.id,due:'2026-10-26T00:00:00.000Z',source:stored.digest,code:'awaiting_step',missing:'合成管理选择',next_action:'明确是否继续工作'});
  const result=await h.service.abandonRun!(h.alice,run.run,question.digest,'不再追求本次目标');
  const current=result.result.partitions.delivered[0].requirements[0].layers[0];
  assert.equal(current.terminal,'unchecked');assert.deepEqual(current.exit?.audience,{user:h.alice.id});assert.equal(current.exit?.due,question.body.due);
  assert.equal(partitionCountsOf(result.result.partitions).unknown,partitionCountsOf(old.partitions).unknown);
  assert.deepEqual((await h.kit.store.get(record.digest))!.body,old);
  assert.equal(old.partitions.delivered[0].requirements[0].layers[0].exit,undefined);
});

test('an interrupted management projection is visible and recovered without repeating the human choice', {skip},async t=>{
  const map=await h.upload(h.alice,toyMap(standardDocument()));
  const run=(await h.service.startRun(h.alice,{pack:'toy-locate',inputs:{map:{reference:map}}},h.call())).run!;
  const stored=(await runById(h.kit.store,run.run))!;
  const requests=createRequestService(h.kit),question=await requests.write({run:run.run,kind:'disposition',audience:h.alice.id,due:'2026-10-26T00:00:00.000Z',source:stored.digest,code:'awaiting_step',missing:'合成投影恢复',next_action:'管理放弃'});
  const put=h.kit.store.put.bind(h.kit.store);let fail=true;
  t.mock.method(h.kit.store,'put',async(...args:Parameters<typeof put>)=>{if(fail&&args[0].kind==='validation_result'&&(args[0].body as {system_input?:string}).system_input){fail=false;throw new Error('SyntheticManagementStoreFailure');}return put(...args);});
  await assert.rejects(h.service.abandonRun!(h.alice,run.run,question.digest,'同一管理决定只记一次'),/SyntheticManagementStoreFailure/);
  const pending=(await h.service.getRun(h.alice,run.run))!;assert.ok(pending.management);assert.equal(pending.latest,null);
  await h.service.maintain();
  const restored=(await h.service.getRun(h.alice,run.run))!;assert.ok(restored.latest?.result.system_input);
  assert.equal((await requests.inspect(question.digest))!.answered_by,pending.management!.record);
});

test('three failed management projections hand the exact remaining work to a named administrator', {skip},async t=>{
  const map=await h.upload(h.alice,toyMap(standardDocument()));
  const run=(await h.service.startRun(h.alice,{pack:'toy-locate',inputs:{map:{reference:map}}},h.call())).run!;
  const stored=(await runById(h.kit.store,run.run))!,requests=createRequestService(h.kit);
  const question=await requests.write({run:run.run,kind:'disposition',audience:h.alice.id,due:'2026-10-26T00:00:00.000Z',source:stored.digest,code:'awaiting_step',missing:'合成管理交付',next_action:'明确管理选择'});
  const put=h.kit.store.put.bind(h.kit.store);
  const mock=t.mock.method(h.kit.store,'put',async(...args:Parameters<typeof put>)=>{if(args[0].kind==='validation_result'&&(args[0].body as {system_input?:string}).system_input)throw new Error('SyntheticPersistentProjectionFailure');return put(...args);});
  await assert.rejects(h.service.abandonRun!(h.alice,run.run,question.digest,'合成管理选择'));
  for(let n=0;n<4;n++)await h.service.maintain();
  const pending=(await h.service.getRun(h.alice,run.run))!;
  const repair=(await requests.all(run.run)).find(q=>q.kind==='repair'&&q.source===pending.management!.record)!;
  assert.ok(repair);assert.equal(repair.audience,h.admin.id);assert.ok(repair.next_action.includes('run abandon'));
  assert.equal(pending.latest,null);
  mock.mock.restore();
  await h.service.abandonRun!(h.alice,run.run,question.digest,'合成管理选择');
  await h.service.maintain();
  assert.ok((await requests.inspect(repair.record))!.answered_by,'the actual recovered management delivery answers its repair request');
});

import assert from 'node:assert/strict';
import {test} from 'node:test';
import {RunRecord} from '../../../contracts/src/run.ts';
import {runRecord,TRACE,H} from '../../../contracts/src/fixtures.ts';
import type {Submission} from '../../../contracts/src/submission.ts';
import {startPostgres} from '../../testing/postgres.ts';
import {openHarness} from './testing/harness.ts';
import {createEngineContext} from './deps.ts';
import {evaluate} from './evaluate.ts';
import {createRunsService} from './service.ts';
import {putRun,actionsOf} from './store.ts';
import {authorOriginOf} from './lineage.ts';
const table={schema:'range@1',origin:'合成规则',checks:[{values:'$.fields.value',range:{minimum:1,maximum:3}}]};
test('runtime admission reruns contrasting bound items and records observed source provenance',async t=>{
 const pg=await startPostgres();t.after(()=>pg.stop());const h=await openHarness(pg);t.after(()=>h.close());
 const source=await h.kit.artifacts.ingest({bytes:new TextEncoder().encode('{"positive":1,"negative":9}'),mediaType:'application/json',origin:{read:{object:'synthetic:document:sample@1'}},author:{user:null},provenanceType:'observed',visibility:{readers:[h.alice.id],admins:true,packs:[],shareable:false}});
 const reference=`src:${source.body.sha256}`;
 const requirement={key:'r',name:'合成要求',description:'合成',target:'item' as const,required:true,done_rule:'bookkeeping' as const,layers:['static' as const],accepted_producer:'fact' as const,checks:[],error_handling:[],run_table:true};
 const workflow={...h.review,requirements:[requirement],checks:[],slots:{...h.review.slots,item:{},run:{}},ledger:{schema:'ledger@1' as const,shapes:[{requirement:'r',interpreter:'range@1',ruled_in:'10.6.0'}]}};
 const run=RunRecord.parse({...runRecord,pack:'synthetic@10.6.0',product:'synthetic',version:'10.6',build:'SYNTHETIC_10_6_0',runner:h.alice.id,sources:[{reference,role:'subject'}],requirements:[],items:[{id:'positive',label:'正例',location:reference,fields:{value:1}},{id:'negative',label:'反例',location:reference,fields:{value:9}}]});
 const submission:Submission={run:run.run,model:'synthetic',items:run.items.map(item=>({item:item.id,handling:'handled',slots:{}})),checks:[{requirement:'r',interpreter:'range@1',table,samples:[{item:'positive',expect:[{verdict:'support'}]},{item:'negative',expect:[{verdict:'refute'}]}]}]};
 const ctx=createEngineContext({records:h.kit,workflows:h.workflows,packs:h.packs,knowledge:h.knowledge,external:h.external,sandbox:{requireOsIsolation:false}});
 const input={run,workflow,submission,submissionDigest:H,exact:null,carried:new Map(),roundsUsed:new Map(),origin:{sessions:['synthetic'],model:'synthetic'},author:null,traceId:TRACE};
 const checked=await evaluate(ctx,input);
 assert.equal(checked.runtimeAdmission[0].samples[0].outcome[0].verdict,'support');
 assert.equal(checked.runtimeAdmission[0].samples[1].outcome[0].verdict,'refute');
 assert.equal(checked.runtimeAdmission[0].samples[0].source_provenance?.record,source.digest);
 assert.match(checked.runtimeAdmission[0].table_sha256,/^[a-f0-9]{64}$/);
 assert.equal(checked.runtimeAdmission[0].samples.every(sample=>sample.passed),true);
 assert.equal(checked.runtimeAdmission[0].admitted,true);
 assert.equal(checked.runtimeAdmission[0].samples[0].source_provenance?.outside_author,true);
 const wrongPositive=structuredClone(submission);wrongPositive.checks![0].samples[0].expect=[{verdict:'refute'}];
 assert.equal((await evaluate(ctx,{...input,submission:wrongPositive})).runtimeAdmission[0].samples[0].passed,false);
 const wrongNegative=structuredClone(submission);wrongNegative.checks![0].samples[1].expect=[{verdict:'support'}];
 assert.equal((await evaluate(ctx,{...input,submission:wrongNegative})).runtimeAdmission[0].samples[1].passed,false);
 const workflows={byDigest:async()=>workflow,forUser:async()=>workflow,summaries:async()=>[],ownerOf:async()=>h.admin.id};
 const service=createRunsService({...ctx.deps,workflows});
 await putRun(h.kit.store,run,new Date().toISOString());
 const answer=await service.submitResult(h.alice,submission,h.call('synthetic'));
 assert.equal(answer.acceptance,'accepted',JSON.stringify(answer.errors));
 const actions=(await actionsOf(h.kit.store,run.run)).filter(action=>action.body.action==='validate');
 assert.equal(actions.length,1);
 assert.equal((actions[0].body.detail.admission as Array<{admitted:boolean}>)[0].admitted,true);
 const author=await authorOriginOf(ctx,{...run,pack:'verification@10.6.0',predecessor:run.run});
 assert.equal(author?.complete,true);
 assert.ok(author?.models.has('synthetic'));
 const authored=await h.upload(h.alice,new TextEncoder().encode('synthetic author samples'));
 const authorRun={...run,sources:[{reference:authored,role:'subject' as const}],items:run.items.map(item=>({...item,location:authored}))};
 const authoredResult=await evaluate(ctx,{...input,run:authorRun});
 assert.equal(authoredResult.runtimeAdmission[0].samples[0].source_provenance?.outside_author,false);
 assert.equal(authoredResult.runtimeAdmission[0].admitted,false);
});

// Negative ownership cases from the independent review: a hash in metadata is not an independently held object.
import assert from 'node:assert/strict';
import {before,after,test} from 'node:test';
import {mkdtemp,rm,access} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {Database,createPool} from './db.ts';
import {migrate,MIGRATIONS} from './migrations.ts';
import {canonicalize} from './canonical.ts';
import {recordDigest} from './digest.ts';
import {newId} from './ids.ts';
import {PgPrincipals} from './principals.ts';
import {FileObjectStore} from './objects.ts';
import {openRecords} from './index.ts';
import {DEFAULT_LIMITS} from '../config/index.ts';
import {startPostgres} from '../testing/postgres.ts';
import {INITIAL_PERSONAL_EPOCH} from './personal-payloads.ts';
let postgres:Awaited<ReturnType<typeof startPostgres>>;
before(async()=>{postgres=await startPostgres();});after(()=>postgres?.stop());
for(const mention of ['generated-input','filename','node-prose'] as const)test(`retirement removes a private original mentioned only in ${mention}`,async t=>{
 const database=await postgres.createDatabase(undefined,{empty:true}),db=new Database(createPool(database));t.after(()=>db.end());
 const dataDir=await mkdtemp(join(tmpdir(),'synthetic-mentioned-upgrade-'));t.after(()=>rm(dataDir,{recursive:true,force:true}));
 await migrate(db,MIGRATIONS.slice(0,13));const at='2026-11-03T00:00:00.000Z';
 const {user}=await new PgPrincipals(db,()=>new Date(at)).bootstrapAdmin('synthetic-owner');
 async function old(kind:string,schema:string,body:unknown){const text=canonicalize(body),digest=recordDigest({kind,schema,provenance:'declared',created_at:at,body});
  await db.query('INSERT INTO records(id,digest,kind,schema,provenance,created_at,body,size) VALUES($1,$2,$3,$4,$5,$6,$7,$8)',[newId('rcd'),digest,kind,schema,'declared',at,text,Buffer.byteLength(text)]);return digest;
 }
 const objects=new FileObjectStore(join(dataDir,'objects'),db,{maxBytes:DEFAULT_LIMITS.maxUploadBytes,now:()=>new Date(at)});
 const bytes=Buffer.from('synthetic private original'),hash=(await objects.put(bytes,'text/plain')).sha256;
 const body={sha256:hash,size:bytes.length,media_type:'text/plain',name:'synthetic-private.txt',origin:{upload:{session:null,message:null}},author:{user:user.id,declared:null},provenance_type:'declared',captured_at:at,read_tier:'model_readable',visibility:{readers:[user.id],admins:false,packs:[],shareable:false},scan:{scanner:'credential-scan@3',inspected:true,clean:true,findings:[],truncated:false}};
 const artifact=await old('source_artifact','source_artifact@1',body);
 await old('knowledge_space_source','knowledge-space-source@1',{space:user.id,path:'/',sha256:hash,artifact,size:bytes.length,by:user.id,at});
 const otherBytes=Buffer.from('synthetic independent generated bytes'),other=(await objects.put(otherBytes,'text/plain')).sha256;
 const independent=await old('source_artifact','source_artifact@1',{...body,sha256:other,size:otherBytes.length,name:mention==='filename'?'synthetic-'+hash+'.txt':'synthetic-derived.txt',origin:{generated:{generator:'synthetic@1',inputs:mention==='generated-input'?['src:'+hash]:[]}},author:{user:null,declared:null},visibility:{readers:[],admins:true,packs:[],shareable:false}});
 if(mention==='node-prose')await old('tree_node','tree_node@1',{description:'synthetic mention '+hash});
 await migrate(db);const kit=await openRecords({database,dataDir,logDir:join(dataDir,'logs'),limits:{...DEFAULT_LIMITS}},{migrate:false});t.after(()=>kit.close());
 await kit.personalPayloads!.purge(user,INITIAL_PERSONAL_EPOCH);
 await assert.rejects(access(objects.path(hash)));assert.equal(await kit.objects.get(hash),null);assert.equal(await kit.store.get(artifact),null);
 assert.ok(await kit.store.get(independent));assert.deepEqual(Buffer.from((await kit.objects.get(other))!),otherBytes);
});

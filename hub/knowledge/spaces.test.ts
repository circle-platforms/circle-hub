const note = (statement: string, path = '/') => ({ kind: 'observation', statement, path });
test('owners, directory grantees, administrators and revoked readers have independent boundaries for identical content', async (t) => {
  const w = await makeWorld(postgres);
  t.after(w.close);
  const spaces = w.knowledge.spaces!;
  const first = await spaces.write(w.user, note('合成共享观察', '/notes'));
  const second = await spaces.write(w.outsider, note('合成共享观察', '/notes'));
  assert.equal(first.entry, second.entry);
  assert.notEqual(first.root, second.root);
  const hidden = await spaces.write(w.user, note('合成私有观察', '/notes-private'));
  const read = (by: typeof w.user, root = first.root, path = '/notes') => w.knowledge.getNodes({ root, paths: [path], depth: 0 }, by);
  assert.equal(await read(w.admin), null);
  assert.equal(await read(w.outsider), null);
  assert.equal((await read(w.user))?.nodes[0].entries[0].statement, '合成共享观察');
  await spaces.grant(w.user, { path: '/notes', audience: 'member', member: w.outsider.id });
  assert.equal((await read(w.outsider))?.nodes[0].entries[0].statement, '合成共享观察');
  assert.equal((await read(w.outsider, hidden.root, '/notes-private'))?.nodes.length, 0);
  assert.equal(await read(w.admin), null);
  const found = await spaces.search(w.outsider, '共享观察', 'shared');
  assert.equal(found.matches.length, 1);
  assert.equal(found.matches[0].space, w.user.id);
  const parsed = GetNodesOutput.safeParse({ call_result: 'ok', errors: [], trace: '1'.repeat(32), root: first.root, ...(await read(w.outsider)) });
  assert.ok(parsed.success, parsed.error?.message);
  await spaces.grant(w.user, { path: '/notes', audience: 'member', member: w.outsider.id, revoke: true });
  assert.equal(await read(w.outsider), null);
  assert.equal((await spaces.search(w.outsider, '共享观察', 'shared')).matches.length, 0);
  await spaces.grant(w.user, { path: '/', audience: 'administrators' });
  assert.ok(await read(w.admin));
  await spaces.grant(w.user, { path: '/', audience: 'administrators', revoke: true });
  assert.equal(await read(w.admin), null);
});

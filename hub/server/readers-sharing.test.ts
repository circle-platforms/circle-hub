import assert from 'node:assert/strict';
import { after, before, test } from 'node:test';
import { startPostgres, type TemporaryPostgres } from '../testing/postgres.ts';
import { openHarness, sandboxSkip } from '../runs/engine/testing/harness.ts';
import { standardDocument, toyMap } from '../runs/engine/testing/mindmap.ts';
import { sourceReaderFor, recordReaderFor } from './readers.ts';
import { recordDigest } from '../refs/api.ts';
let postgres: TemporaryPostgres;
const skip = await sandboxSkip();
before(async () => { postgres = await startPostgres(); });
after(async () => { await postgres?.stop(); });

test('a shared run grants only its generated bytes and preserves exact record bodies and reader tiers', {skip}, async t => {
  const h = await openHarness(postgres); t.after(() => h.close());
  const bytes = toyMap(standardDocument());
  const generated = await h.kit.artifacts.ingest({bytes,mediaType:'application/json',origin:{generated:{generator:'synthetic-view@1',inputs:[]}},author:{user:null},provenanceType:'projected',visibility:{readers:[h.alice.id],admins:false,packs:[],shareable:false}});
  const sha = generated.body.sha256;
  const run = (await h.service.startRun(h.alice,{pack:'toy-locate',inputs:{map:{reference:'src:'+sha}}},h.call())).run!;
  await h.kit.authorizations.share(h.admin,run.run,{kind:'pack_users',pack:'toy-locate'});
  const reader = {user:h.bob.id,role:h.bob.role,run:run.run};
  const sources = sourceReaderFor(h.kit,h.bob,'model');
  assert.equal(await sources.read(sha,reader),null);
  await h.kit.authorizations.assign(h.admin,h.bob.id,'toy-locate');
  assert.deepEqual(Buffer.from((await sources.read(sha,reader))!.bytes!),Buffer.from(bytes));
  assert.equal(await sources.read(sha,{user:h.bob.id,role:h.bob.role}),null);
  assert.equal(await sources.read(sha,{...reader,run:'run_'+'1'.repeat(26)}),null);
  assert.equal(await h.kit.artifacts.source(h.bob,sha),null);
  const unrelated = await h.kit.artifacts.ingest({bytes:Buffer.from('unbound synthetic evidence'),mediaType:'text/plain',origin:{generated:{generator:'synthetic-view@1',inputs:[]}},author:{user:null},provenanceType:'projected',visibility:{readers:[h.alice.id],admins:false,packs:[],shareable:false}});
  assert.equal(await sources.read(unrelated.body.sha256,reader),null);
  assert.deepEqual((await h.kit.artifacts.records(sha))[0].body.visibility,generated.body.visibility);
  const quoted = await h.service.resolveReference(h.bob,{run:run.run,text:'设置 3 区浇灌',expect:'quotation'},h.call());
  assert.equal(quoted.call_result,'ok'); assert.ok(quoted.references.length>0,JSON.stringify(quoted));
  const stored = (await h.kit.store.find({kind:'run',key:'runs.id',value:run.run,limit:1})).items[0];
  const records = recordReaderFor(h.kit,h.service,h.bob);
  const visible = await records.read(stored.digest,reader); assert.ok(visible);
  assert.equal(recordDigest(visible),stored.digest);
  const rejected = await h.service.submitResult(h.alice,{run:run.run,model:'synthetic',items:[{item:'unlisted',handling:'handled',slots:{}}]},h.call());
  assert.equal(rejected.acceptance,'not_accepted');
  const refused = (await h.kit.store.find<{acceptance:string}>({kind:'validation_result',key:'runs.result.run',value:run.run,limit:100})).items.find(r=>r.body.acceptance==='not_accepted')!;
  assert.ok(refused); assert.equal(await records.read(refused.digest,reader),null);
  assert.ok(await recordReaderFor(h.kit,h.service,h.alice).read(refused.digest,{user:h.alice.id,role:h.alice.role}));
  await h.kit.authorizations.unassign(h.admin,h.bob.id,'toy-locate');
  assert.equal(await sources.read(sha,reader),null); assert.equal(await records.read(stored.digest,reader),null);
  await h.kit.principals.setRole(h.admin,h.bob.id,'admin');
  const stale = recordReaderFor(h.kit,h.service,{...h.bob,role:'admin'});
  assert.ok(await stale.read(stored.digest,reader));
  await h.kit.principals.setRole(h.admin,h.bob.id,'user');
  assert.equal(await stale.read(stored.digest,reader),null);
});

test('sharing a run does not expose connector originals even when they are bound', {skip}, async t => {
  const h = await openHarness(postgres); t.after(() => h.close());
  const artifact = await h.kit.artifacts.ingest({bytes:toyMap(standardDocument()),mediaType:'application/json',origin:{read:{object:'synthetic:map:private'}},author:{user:null},provenanceType:'observed',visibility:{readers:[h.alice.id],admins:false,packs:[],shareable:false}});
  const run = (await h.service.startRun(h.alice,{pack:'toy-locate',inputs:{map:{reference:'src:'+artifact.body.sha256}}},h.call())).run!;
  await h.kit.authorizations.share(h.admin,run.run,[h.bob.id]);
  assert.ok(await h.service.getRun(h.bob,run.run));
  assert.equal(await sourceReaderFor(h.kit,h.bob).read(artifact.body.sha256,{user:h.bob.id,role:h.bob.role,run:run.run}),null);
});

test('Hub-rendered record inputs retain their user author and are shared through the verified projected digest', {skip}, async t => {
  const h=await openHarness(postgres);t.after(()=>h.close());
  const source=await h.upload(h.alice,toyMap(standardDocument()));
  const first=(await h.service.startRun(h.alice,{pack:'toy-locate',inputs:{map:{reference:source}}},h.call())).run!;
  const result=(await h.service.getRun(h.alice,first.run))!.production!;
  const {writeFile}=await import('node:fs/promises');const {join}=await import('node:path');
  await writeFile(join(h.locate.pack.directory,'functions/record-input.ts'),"export default input => ({items:[{id:'record',label:'合成记录',location:{parser:'json@1',selector:'p'},fields:{path:['root','record'],expected:['合成期望']}}],warnings:[]});");
  h.locate.workflow.projection={module:'functions/record-input.ts'};
  const started=await h.service.startRun(h.alice,{pack:'toy-locate',inputs:{map:{reference:'rec:'+result.record}}},h.call());
  assert.equal(started.call_result,'ok',JSON.stringify(started.errors));
  const run=started.run!;assert.ok(run.sources[0].reference.startsWith('rec:'));
  const sha=/^src:([0-9a-f]{64})/.exec(run.items[0].location)![1];
  const generated=(await h.kit.artifacts.records(sha)).find(a=>'generated' in a.body.origin)!;
  assert.equal(generated.body.author.user,h.alice.id);
  await h.kit.authorizations.share(h.admin,run.run,[h.bob.id]);
  const read=await sourceReaderFor(h.kit,h.bob).read(sha,{user:h.bob.id,role:h.bob.role,run:run.run});
  assert.ok(read?.bytes);assert.equal(await h.kit.artifacts.source(h.bob,sha),null);
});

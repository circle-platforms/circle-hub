// Generates everything that must not be written by hand from the cause model:
//   contracts/generated/vocabulary.ts   the one set of enumerations, with Chinese labels and zod enums
//   contracts/generated/protocol.ts     protocol and core violation codes, reference schemes, record kinds, pack file names
//   contracts/generated/tools.json      the six MCP tools with JSON Schemas and derived annotations
//   contracts/generated/schemas/*.json  JSON Schema of every registered record and pack file shape
// Usage: node tools/gen-contracts.ts [--check]
// --check regenerates in memory and exits 1 when a committed file differs.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

type Value = { code: string; label: string };
type Axis = { axis: string; label: string; owner: string; values: Value[] };
type Model = {
  version: number;
  vocabulary: Axis[];
  formatProposals: {
    references: { scheme: string; form: string; example?: string; note?: string }[];
    protocolCodes: { code: string; when: string; fix: string }[];
    recordKinds: string[];
    packFiles: { path: string; content: string; elements: string[] }[];
    displayOrder: string[];
  };
};
type Codes = { codes: { code: string; interpreter: string; when: string; fix: string }[] };

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const GENERATED = join(ROOT, 'contracts', 'generated');
const HEADER = '// Generated by tools/gen-contracts.ts from contracts/model.json and contracts/codes.json. Do not edit.\n';
const check = process.argv.includes('--check');

const model: Model = JSON.parse(readFileSync(join(ROOT, 'contracts', 'model.json'), 'utf8'));
const codes: Codes = JSON.parse(readFileSync(join(ROOT, 'contracts', 'codes.json'), 'utf8'));

const q = (s: string): string => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const pascal = (s: string): string => s.split('_').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const upper = (s: string): string => s.toUpperCase();

function vocabulary(): string {
  const out: string[] = [HEADER, "import { z } from 'zod';\n"];
  out.push('export const AXES = {');
  for (const a of model.vocabulary) {
    out.push(`  ${a.axis}: { label: ${q(a.label)}, owner: ${q(a.owner)}, values: [${a.values.map((v) => `{ code: ${q(v.code)}, label: ${q(v.label)} }`).join(', ')}] },`);
  }
  out.push('} as const;\n', 'export type AxisName = keyof typeof AXES;\n');
  for (const a of model.vocabulary) {
    const C = upper(a.axis);
    const T = pascal(a.axis);
    out.push(`/** ${a.label} (${a.owner}) */`);
    out.push(`export const ${C} = [${a.values.map((v) => q(v.code)).join(', ')}] as const;`);
    out.push(`export type ${T} = (typeof ${C})[number];`);
    out.push(`export const ${C}_LABEL = { ${a.values.map((v) => `${q(v.code)}: ${q(v.label)}`).join(', ')} } as const satisfies Record<${T}, string>;`);
    out.push(`export const ${T}Schema = z.enum(${C});`);
    out.push(`export function is${T}(value: unknown): value is ${T} {\n  return (${C} as readonly unknown[]).includes(value);\n}\n`);
  }
  out.push('export interface AxisValues {');
  for (const a of model.vocabulary) out.push(`  ${a.axis}: ${pascal(a.axis)};`);
  out.push('}\n');
  out.push('const LABELS: { [A in AxisName]: Readonly<Record<AxisValues[A], string>> } = {');
  for (const a of model.vocabulary) out.push(`  ${a.axis}: ${upper(a.axis)}_LABEL,`);
  out.push('};\n');
  out.push('/** Chinese display label of a vocabulary code. The only place labels come from. */');
  out.push('export function labelOf<A extends AxisName>(axis: A, code: AxisValues[A]): string {\n  return LABELS[axis][code];\n}\n');
  out.push('export function axisLabel(axis: AxisName): string {\n  return AXES[axis].label;\n}\n');
  return out.join('\n');
}

function protocol(): string {
  const out: string[] = [HEADER];
  const pc = model.formatProposals.protocolCodes;
  out.push('export const PROTOCOL_CODES = {');
  for (const c of pc) out.push(`  ${c.code}: { when: ${q(c.when)}, fix: ${q(c.fix)} },`);
  out.push('} as const;\n', 'export type ProtocolCode = keyof typeof PROTOCOL_CODES;\n');
  out.push('export const CORE_VIOLATION_CODES = {');
  for (const c of codes.codes) out.push(`  ${q(c.code)}: { interpreter: ${q(c.interpreter)}, when: ${q(c.when)}, fix: ${q(c.fix)} },`);
  out.push('} as const;\n', 'export type CoreViolationCode = keyof typeof CORE_VIOLATION_CODES;\n');
  out.push(`export const REFERENCE_FORMS = {${model.formatProposals.references.map((r) => `\n  ${r.scheme}: ${q(r.form)}`).join(',')}\n} as const;\n`);
  out.push(`export const RECORD_KINDS = [${model.formatProposals.recordKinds.map(q).join(', ')}] as const;`);
  out.push('export type RecordKind = (typeof RECORD_KINDS)[number];\n');
  out.push(`export const PACK_FILE_PATHS = [${model.formatProposals.packFiles.map((f) => q(f.path)).join(', ')}] as const;\n`);
  out.push(`export const DISPLAY_ORDER = [${model.formatProposals.displayOrder.map(q).join(', ')}] as const;\n`);
  out.push(`export const MODEL_VERSION = ${model.version};\n`);
  return out.join('\n');
}

async function schemasAndTools(): Promise<Record<string, string>> {
  const index = join(ROOT, 'contracts', 'src', 'index.ts');
  const files: Record<string, string> = {};
  if (!existsSync(index)) return files;
  const { z } = await import('zod');
  const src = (await import(pathToFileURL(index).href)) as {
    TOOLS: { name: string; title: string; description: string; input: unknown; output: unknown; effect: string; writesHubRecords: boolean; readsExternal?: boolean; idempotent?: boolean }[];
    SCHEMA_REGISTRY: Record<string, unknown>;
    annotationsFor: (effect: string, writesHubRecords: boolean, options?: { readsExternal?: boolean; idempotent?: boolean }) => Record<string, boolean>;
  };
  const js = (schema: unknown): unknown => z.toJSONSchema(schema as never, { target: 'draft-2020-12', io: 'input', unrepresentable: 'any' });
  const jsOut = (schema: unknown): unknown => z.toJSONSchema(schema as never, { target: 'draft-2020-12', io: 'output', unrepresentable: 'any' });
  const tools = src.TOOLS.map((t) => ({
    name: t.name,
    title: t.title,
    description: t.description,
    inputSchema: js(t.input),
    outputSchema: jsOut(t.output),
    annotations: src.annotationsFor(t.effect, t.writesHubRecords, { readsExternal: t.readsExternal ?? false, idempotent: t.idempotent ?? false }),
  }));
  files['tools.json'] = `${JSON.stringify(tools, null, 2)}\n`;
  for (const [id, schema] of Object.entries(src.SCHEMA_REGISTRY).sort(([a], [b]) => (a < b ? -1 : 1))) {
    files[`schemas/${id.replace('@', '.v')}.schema.json`] = `${JSON.stringify(jsOut(schema), null, 2)}\n`;
  }
  return files;
}

const files: Record<string, string> = {
  'vocabulary.ts': vocabulary(),
  'protocol.ts': protocol(),
};

if (check) {
  // Stage 2 imports contracts/src, which imports the generated vocabulary: it must exist and be current first.
  const onDisk = (name: string): string | null => (existsSync(join(GENERATED, name)) ? readFileSync(join(GENERATED, name), 'utf8') : null);
  for (const name of ['vocabulary.ts', 'protocol.ts']) {
    if (onDisk(name) !== files[name]) {
      console.error(`contracts/generated/${name} is out of date; run npm run gen:contracts`);
      process.exit(1);
    }
  }
}

Object.assign(files, await schemasAndTools());

if (check) {
  const expected = new Set(Object.keys(files));
  const present = new Set<string>();
  const walk = (dir: string, prefix: string): void => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      if (e.isDirectory()) walk(join(dir, e.name), `${prefix}${e.name}/`);
      else present.add(`${prefix}${e.name}`);
    }
  };
  if (existsSync(GENERATED)) walk(GENERATED, '');
  const problems: string[] = [];
  for (const name of expected) {
    const p = join(GENERATED, name);
    if (!existsSync(p) || readFileSync(p, 'utf8') !== files[name]) problems.push(`out of date: contracts/generated/${name}`);
  }
  for (const name of present) if (!expected.has(name)) problems.push(`stale generated file: contracts/generated/${name}`);
  if (problems.length) {
    console.error(`${problems.join('\n')}\nrun npm run gen:contracts`);
    process.exit(1);
  }
  console.log(`contracts/generated matches the model (${expected.size} files)`);
} else {
  rmSync(join(GENERATED, 'schemas'), { recursive: true, force: true });
  for (const [name, text] of Object.entries(files)) {
    const p = join(GENERATED, name);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, text);
  }
  console.log(`wrote ${Object.keys(files).length} files to contracts/generated`);
}

// Writes the error-code table of docs/protocols/knowledge-sync-v1.md from the registered protocol codes
// (contracts/generated/protocol.ts, generated from contracts/model.json) and the sync HTTP statuses
// (PERSONAL_SYNC_ERROR_STATUS in contracts/src/sync.ts). `--check` exits 1 when the page differs; the docs checks
// (.github/checks/docs.test.ts) run the same comparison.
import {readFileSync,writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {PROTOCOL_CODES} from '../contracts/generated/protocol.ts';
import {PERSONAL_SYNC_ERROR_STATUS} from '../contracts/src/sync.ts';

export const SYNC_SPEC_PAGE='docs/protocols/knowledge-sync-v1.md';
export const TABLE_BEGIN='<!-- BEGIN sync-error-table: generated by `node tools/gen-sync-error-table.ts`; do not edit -->';
export const TABLE_END='<!-- END sync-error-table -->';
const ROOT=fileURLToPath(new URL('../',import.meta.url));
const cell=(text:string)=>text.replaceAll('|','\\|').replaceAll('\n',' ');

/** The table rows in the order PERSONAL_SYNC_ERROR_STATUS lists them. */
export function renderSyncErrorTable():string{
 const codes=PROTOCOL_CODES as Record<string,{when:string;fix:string}>;
 const rows=Object.entries(PERSONAL_SYNC_ERROR_STATUS).map(([code,status])=>{
  const text=codes[code];if(!text)throw new Error(`${code} is not a registered protocol code`);
  return `| \`${code}\` | ${status} | ${cell(text.when)} | ${cell(text.fix)} |`;
 });
 return [TABLE_BEGIN,'','| Code | HTTP status | Registered text (`when`) | Registered next step (`fix`) |','|---|---|---|---|',...rows,'',TABLE_END].join('\n');
}

/** The page with its table section replaced; throws when the markers are missing or repeated. */
export function withSyncErrorTable(page:string):string{
 const begin=page.indexOf(TABLE_BEGIN),end=page.indexOf(TABLE_END);
 if(begin<0||end<begin||page.indexOf(TABLE_BEGIN,begin+1)>=0||page.indexOf(TABLE_END,end+1)>=0)throw new Error(`${SYNC_SPEC_PAGE} needs exactly one ${TABLE_BEGIN} … ${TABLE_END} section`);
 return page.slice(0,begin)+renderSyncErrorTable()+page.slice(end+TABLE_END.length);
}

/** Problems of the page's table against the registry: empty when it is current. */
export function syncErrorTableProblems(page:string):string[]{
 let expected:string;try{expected=withSyncErrorTable(page);}catch(error){return [(error as Error).message];}
 return expected===page?[]:[`${SYNC_SPEC_PAGE}: the error-code table differs from the registered codes; run node tools/gen-sync-error-table.ts`];
}

if(process.argv[1]&&fileURLToPath(import.meta.url)===process.argv[1]){
 const path=join(ROOT,SYNC_SPEC_PAGE),page=readFileSync(path,'utf8');
 if(process.argv.includes('--check')){const problems=syncErrorTableProblems(page);for(const p of problems)console.error(p);process.exit(problems.length?1:0);}
 const next=withSyncErrorTable(page);if(next!==page)writeFileSync(path,next);console.log(next===page?`${SYNC_SPEC_PAGE}: table current`:`${SYNC_SPEC_PAGE}: table written`);
}
